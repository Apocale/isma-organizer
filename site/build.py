"""Builds the website into site/dist: the page, and engine.js, which carries
the panel's REAL host script (PremiereProOrganizer/OrganizeFilesInProject.jsx)
so the demo on the page runs the same code as Premiere.

    python3 site/build.py
"""
import json, os, shutil

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DIST = os.path.join(HERE, 'dist')

os.makedirs(os.path.join(DIST, 'assets'), exist_ok=True)
shutil.copyfile(os.path.join(HERE, 'src', 'index.html'), os.path.join(DIST, 'index.html'))
with open(os.path.join(ROOT, 'PremiereProOrganizer', 'OrganizeFilesInProject.jsx'), encoding='utf-8') as f:
    jsx = f.read()
with open(os.path.join(DIST, 'engine.js'), 'w', encoding='utf-8') as f:
    f.write('// Generated by site/build.py from PremiereProOrganizer/OrganizeFilesInProject.jsx\n')
    f.write('window.ISMA_ENGINE = ' + json.dumps(jsx) + ';\n')
src_assets = os.path.join(HERE, 'assets')
if os.path.isdir(src_assets):
    for name in os.listdir(src_assets):
        shutil.copyfile(os.path.join(src_assets, name), os.path.join(DIST, 'assets', name))
open(os.path.join(DIST, '.nojekyll'), 'w').close()
print('built', DIST)
